import assert from 'node:assert/strict'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve, relative } from 'node:path'
import { createHash } from 'node:crypto'

const root = fileURLToPath(new URL('../', import.meta.url))
const read = path => {
  assert.ok(!relative(root, resolve(root, path)).startsWith('..'), `Path outside repository: ${path}`)
  return readFile(resolve(root, path), 'utf8')
}
const checklist = JSON.parse(await read('test/spec-coverage.json'))
const manifest = JSON.parse(await read('test/reference-assets.json'))
const statuses = ['implemented', 'partial', 'unsupported', 'unverified']
assert.equal(checklist.schemaVersion, 1)
assert.match(manifest.revision, /^[0-9a-f]{40}$/)
const assets = new Set()
for (const asset of manifest.assets) {
  assert.ok(!assets.has(asset.name), `Duplicate asset: ${asset.name}`)
  assets.add(asset.name)
  const source = await read(`test/fixtures/${asset.name}.gltf`)
  assert.equal(createHash('sha256').update(source).digest('hex'), asset.sha256, `Changed fixture: ${asset.name}`)
  assert.ok(asset.sourceFiles.length > 0, `Missing provenance: ${asset.name}`)
  for (const file of asset.sourceFiles) assert.match(file.sha256, /^[0-9a-f]{64}$/)
}
const counts = Object.fromEntries(statuses.map(status => [status, 0]))
const ids = new Set()
for (const item of checklist.items) {
  assert.match(item.id, /^[A-Z]+-\d{2}$/)
  assert.ok(!ids.has(item.id), `Duplicate ID: ${item.id}`)
  ids.add(item.id)
  assert.ok(statuses.includes(item.status), `Invalid status: ${item.id}`)
  assert.ok(item.behavior && item.implementation.length, `Missing behavior or implementation: ${item.id}`)
  assert.ok(new URL(item.spec).hostname === 'registry.khronos.org' || new URL(item.spec).hostname === 'github.com', `Unexpected spec source: ${item.id}`)
  if (item.status === 'implemented') assert.ok(item.tests.length, `Implemented behavior needs a targeted test: ${item.id}`)
  else assert.ok(item.limitations, `Missing limitation: ${item.id}`)
  for (const file of item.implementation) await read(file)
  for (const evidence of item.tests) {
    const source = await read(evidence.file)
    const names = evidence.file.endsWith('.rs')
      ? [...source.matchAll(/#\[test\]\s*fn\s+(\w+)\s*\(/g)].map(match => match[1])
      : [...source.matchAll(/\btest\(\s*(['"])(.*?)\1\s*,/g)].map(match => match[2])
    assert.ok(names.includes(evidence.name), `Missing test declaration: ${evidence.file}: ${evidence.name}`)
  }
  for (const name of item.references) assert.ok(assets.has(name), `Unknown reference: ${item.id}: ${name}`)
  counts[item.status]++
}
const repo = 'https://github.com/pcbjs/renderer/blob/main/'
const link = (path, label = path) => `[${label}](${repo}${path})`
const lines = [
  '## Detailed checklist',
  '',
  '<!-- Generated by npm run spec:report from test/spec-coverage.json. -->',
  '',
  checklist.scope,
  '',
  `This checklist tracks **${checklist.items.length} behaviors**: ${statuses.map(status => `**${counts[status]} ${status}**`).join(', ')}. These counts are not a percentage of the glTF specification, code coverage, or Khronos certification. Rows vary in scope and are not weighted.`,
  '',
  'Implemented means the named behavior has implementation and targeted regression evidence. Partial means known limits remain. Unsupported means rendering is absent, even when its diagnostic is tested. Unverified means code exists but targeted correctness evidence is missing. None implies exhaustive testing of every valid input.',
  '',
  `The offline reference suite contains **${assets.size} assets**, pinned to [Khronos glTF Sample Assets revision ${manifest.revision.slice(0, 12)}](${manifest.repository}/tree/${manifest.revision}). Source and vendored hashes are recorded in ${link('test/reference-assets.json')}; attribution is in ${link('test/fixtures/NOTICE.md')}. External resources are embedded in text fixtures, then buffers are repacked into one GLB for tests. This does not exercise external resource loading.`,
  '',
  'Every reference is validated before and after repacking with glTF Validator, then rendered from two views with nonempty-output, deterministic-output and expected-diagnostic assertions. These are smoke tests, not reference-image comparisons. Validator results concern asset validity, not renderer conformance.',
  '',
  'Run `npm run build`, `npm test`, and `cargo test` for executable evidence. Run `npm run spec:check` to verify checklist references, pinned fixture hashes and generated documentation; it does not execute the tests. CI runs all four. `npm run spec:report` updates this page and writes `build/spec-coverage.json`, which records inventory counts without claiming a test run passed.',
  '',
  '| ID | Tracked behavior and specification | Status |',
  '| --- | --- | --- |',
  ...checklist.items.map(item => `| [${item.id}](#${item.id.toLowerCase()}) | [${item.behavior}](${item.spec}) | ${item.status} |`),
  '',
]
for (const item of checklist.items) {
  lines.push(
    `### ${item.id}`,
    '',
    `**${item.behavior}: ${item.status}.** [Specification](${item.spec}).`,
    '',
    `Implementation: ${item.implementation.map(path => link(path)).join(', ')}.`,
    '',
  )
  if (item.tests.length) lines.push('Targeted regression evidence:', '', ...item.tests.map(test => `- ${link(test.file, test.name)}`), '')
  if (item.references.length) lines.push(`Reference smoke tests: ${item.references.map(name => link(`test/fixtures/${name}.gltf`, name)).join(', ')}.`, '')
  if (item.limitations) lines.push(`Limitations: ${item.limitations}`, '')
}
const markdown = lines.join('\n')
await mkdir(resolve(root, 'docs/_generated'), { recursive: true })
const path = resolve(root, 'docs/_generated/spec-checklist.md')
if (process.argv.includes('--check')) assert.equal(await readFile(path, 'utf8'), markdown, 'Coverage documentation is stale; run npm run spec:report')
else await writeFile(path, markdown)
await mkdir(resolve(root, 'build'), { recursive: true })
await writeFile(
  resolve(root, 'build/spec-coverage.json'),
  JSON.stringify(
    {
      schemaVersion: 1,
      kind: 'coverage-inventory',
      testsExecuted: false,
      referenceRevision: manifest.revision,
      referenceAssets: assets.size,
      total: checklist.items.length,
      counts,
      items: checklist.items,
    },
    null,
    2,
  ) + '\n',
)
console.log(`Spec inventory checked: ${checklist.items.length} behaviors, ${assets.size} pinned assets; ${statuses.map(status => `${counts[status]} ${status}`).join(', ')}`)
